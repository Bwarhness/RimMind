    public int food;
    public int medicine;
    public int wood;
    public int steel;
    public int colonists;
    public int power;
    public string weather;
}

// Tracks running jokes across weeks
public class RunningJokeTracker : IExposable
{
    public Dictionary<string, int> jokeCount = new Dictionary<string, int>();

    public string GetOngoingJoke()
    {
        if (jokeCount.Count == 0) return null;
        // Return the most frequent joke as the "ongoing" one
        string best = null;
        int bestCount = 0;
        foreach (var kvp in jokeCount)
        {
            if (kvp.Value > bestCount)
            {
                bestCount = kvp.Value;
                best = kvp.Key;
            }
        }
        return best;
    }

    public void AddJoke(string joke)
    {
        if (jokeCount.ContainsKey(joke))
            jokeCount[joke]++;
        else
            jokeCount[joke] = 1;
    }

    public void ExposeData()
    {
        Scribe_Collections.Look(ref jokeCount, "jokeCount");
    }
}
