    public string headline;
    public string leadParagraph;
    public string obituarySection;
    public string battleReport;
    public string milestoneSection;
    public string weatherSection;
    public string lookingAhead;
    public string editorialOpinion;

    // Colonist voices
    public List<ColonistQuote> quotes = new List<ColonistQuote>();

    // Predictions
    public List<Prediction> predictions = new List<Prediction>();

    // Running joke system
    public List<string> runningJokes = new List<string>();
    public string ongoingJoke; // "continuing our ongoing [joke] coverage"

    // Year-ago memory
    public string yearAgoRecap;

    // Meta
