    public bool deathlessWeek;
    public bool firstDeath;

    // Milestones
    public List<string> milestones = new List<string>();
    public bool raidMarathon;
    public bool firstRaidSurvived;

    // Mood
    public float averageMood;
    public string moodiestColonist;
    public string happiestColonist;

    // Resources
    public ResourceSnapshot resources;

    // Weather
    public string weatherSummary;
    public string weatherPoem;

